#!/usr/bin/env python3
"""An OSIL `.flow` as an onto category, checked by onto.

    python3 flow2onto.py thinagent-ci.flow rules.onto-part roles.json > flow.onto
    onto check flow.onto                     # the rules, proved as invariants
    onto functor flow.onto FlowRoles         # the flow mapped into ThinAgentArchitecture

Data values (inputs, consts, outputs, intermediates) become objects; an
operator `a, b -> pkg::Op@0 -> (x, y)` becomes one arrow from every input
to every output, named `op_input_output`. A path in the category is a
route data can take through the flow, so a rule such as "everything that
reaches the decision passed the gate" is a `via` invariant and "the
standard never shapes the proposal" is a `never` invariant.

`rules` holds the invariant lines; `roles.json` maps each data value to a
role of `standards/thin-agent.onto#ThinAgentArchitecture` and is turned
into a functor whose arrows take the shortest allowed route (`id` within
a role). Standard library only.
"""

import json
import re
import sys
from collections import deque
from pathlib import Path

STEP = re.compile(r"^\s*([\w\s,]+?)\s*->\s*(\w+)::(\w+)@\d+\s*->\s*\(?([\w\s,]+?)\)?\s*$")
DECL = re.compile(r"^\s*(input|const|output)\s+(\w+)\s*:")


def parse(flow):
    values, arrows = [], []
    for line in Path(flow).read_text().splitlines():
        line = line.split("//")[0]
        if line.strip().startswith("layout"):
            break
        d = DECL.match(line)
        if d:
            values.append(d.group(2))
            continue
        m = STEP.match(line)
        if m:
            ins = [v.strip() for v in m.group(1).split(",")]
            op = m.group(3)
            outs = [v.strip() for v in m.group(4).split(",")]
            for v in ins + outs:
                if v not in values:
                    values.append(v)
            for i in ins:
                for o in outs:
                    arrows.append((f"{snake(op)}_{i}_{o}", i, o, op))
    return values, arrows


def snake(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def standard_arrows(path, name):
    text = Path(path).read_text()
    body = text[text.index(f"category {name}"):]
    body = body[: body.index("\n}")]
    return re.findall(r"^\s*(\w+):\s*(\w+)\s*->\s*(\w+)", body, re.M)


def route(arrows, src, dst):
    if src == dst:
        return "id"
    seen, queue = {src}, deque([(src, [])])
    while queue:
        node, path = queue.popleft()
        for name, a, b in arrows:
            if a == node and b not in seen:
                if b == dst:
                    return ".".join(reversed(path + [name]))
                seen.add(b)
                queue.append((b, path + [name]))
    return None


def main():
    flow, rules, roles_file = sys.argv[1:4]
    values, arrows = parse(flow)
    roles = json.loads(Path(roles_file).read_text())
    standard = roles.pop("_standard")
    std_path, std_name = standard.split("#")
    std = standard_arrows(Path(roles_file).parent / std_path, std_name)
    missing = [v for v in values if v not in roles]
    if missing:
        sys.exit(f"no role for: {', '.join(missing)}")
    out = [f"# GENERATED by flow2onto.py from {Path(flow).name}, {Path(rules).name}, {Path(roles_file).name}; do not edit.",
           f'import "{std_path}";', "", "category Flow {",
           f"    objects: {', '.join(values)};"]
    out += [f'    {n}: {a} -> {b} "{op}";' for n, a, b, op in arrows]
    out += [f"    {line.strip()}" for line in Path(rules).read_text().splitlines()
            if line.strip() and not line.strip().startswith("#")]
    out += ["}", "", f"functor FlowRoles: Flow -> {std_name} {{",
            f"    objects: {', '.join(f'{v} -> {roles[v]}' for v in values)};"]
    for n, a, b, _ in arrows:
        r = route(std, roles[a], roles[b])
        out.append(f"    {n}: {r or 'id'};" + ("" if r else f"  # the standard allows no {roles[a]} -> {roles[b]}"))
    out += ["    require: invariants;", "}"]
    print("\n".join(out))


if __name__ == "__main__":
    main()
